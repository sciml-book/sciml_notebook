# ── 1. The product K = J J^T ─────────────────────────────────────────────────
def rounded_box(ax, x, y, w, h, r, **kw):
    """Rounded rectangle with lower-left corner (x, y), width w, height h, and corner radius r."""
    ax.add_patch(FancyBboxPatch((x, y), w, h, boxstyle=f"round,pad=0,rounding_size={r}", **kw))


def draw_product(J, i=1, j=2):
    """Draw K = J J^T with each matrix at its true shape, and outline the rows of J that give K_ij."""
    N, P = J.shape
    K = J @ J.T
    x_T, x_K = P + 1.6, P + N + 3.2   # left edges of J^T and K
    fig, ax = plt.subplots(figsize=(5.5, 2.75), constrained_layout=False)
    for name, M, x0, edge, cmap, shape in [(r"\mathbf{J}", J, 0.0, "#3a76b9", plt.cm.Blues, r"$N\times P$"),
                                           (r"\mathbf{J}^\top", J.T, x_T, "#3a76b9", plt.cm.Blues, r"$P\times N$"),
                                           (r"\mathbf{K}", K, x_K, "#4a9a6a", plt.cm.Greens, r"$N\times N$")]:
        rows, cols = M.shape
        top = rows / 2
        rounded_box(ax, x0 - 0.15, -top - 0.15, cols + 0.3, rows + 0.3, 0.35, facecolor=edge, alpha=0.1, edgecolor="none")
        rounded_box(ax, x0 - 0.15, -top - 0.15, cols + 0.3, rows + 0.3, 0.35, facecolor="none", edgecolor=edge, lw=1.5)
        shade = np.abs(M) / np.abs(M).max()   # darker cells hold larger entries
        for r in range(rows):
            for c in range(cols):
                rounded_box(ax, x0 + c + 0.1, top - r - 0.9, 0.8, 0.8, 0.12,
                            facecolor=cmap(0.2 + 0.5 * shade[r, c]), edgecolor="none")
        ax.text(x0 + cols / 2, top + 0.45, f"${name}$", ha="center", va="bottom", fontsize=14)
        ax.text(x0 + cols / 2, -top - 0.45, shape, ha="center", va="top", fontsize=11)
    outline = dict(facecolor="none", edgecolor="#e07b24", lw=1.8)
    rounded_box(ax, 0.05, N / 2 - i - 0.95, P - 0.1, 0.9, 0.2, **outline)        # row i of J
    rounded_box(ax, x_T + j + 0.05, -P / 2 + 0.05, 0.9, P - 0.1, 0.2, **outline)  # column j of J^T
    rounded_box(ax, x_K + j + 0.05, N / 2 - i - 0.95, 0.9, 0.9, 0.2, **outline)   # entry K_ij
    ax.text(P + 0.8, 0, r"$\times$", ha="center", va="center", fontsize=20)
    ax.text(P + N + 2.4, 0, "$=$", ha="center", va="center", fontsize=20)
    ax.text(x_K + N / 2, -N / 2 - 1.5, rf"$K_{{{i+1}{j+1}}} = \sum_{{p=1}}^{{P}} J_{{{i+1}p}}\,J_{{{j+1}p}}$",
            ha="center", va="top", fontsize=11, color="#e07b24")
    ax.set(xlim=(-0.6, x_K + N + 0.6), ylim=(-P / 2 - 1.3, P / 2 + 1.4), aspect="equal")
    ax.axis("off")
    return fig


