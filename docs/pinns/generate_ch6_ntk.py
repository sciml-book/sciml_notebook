report()
report("## Quadratic model u = a x^2 + b x + c, u'' = 2, points x = 0, 1 (boundary) and 1/2 (PDE)")
report()
report(f"J =\n{J_quad}")
report(f"K = J J^T =\n{K_quad}")
report(f"eigenvalues of K_bb = {np.linalg.eigvalsh(K_quad[:2, :2])}  (2 -/+ sqrt 2 = {2 - np.sqrt(2):.3f}, {2 + np.sqrt(2):.3f})")
report(f"K_rr = {K_quad[2, 2]:.0f}")
w_b, w_r = ntk_weights(K_quad, 2)
report(f"tr K_bb = {np.trace(K_quad[:2, :2]):.0f}, tr K_rr = {K_quad[2, 2]:.0f}, NTK weights w_b = {w_b:.3f}, w_r = {w_r:.3f}")
